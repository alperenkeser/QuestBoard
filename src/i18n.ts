export function useTranslation(): (key: TranslationKey | FormTranslationKey) => string {
  const language = useSettingsStore((state) => state.settings?.language ?? "en");
  const dictionary = translations[language as keyof typeof translations] ?? translations.en;
  return (key) => {
    const mainTranslation = dictionary[key as TranslationKey];
    if (mainTranslation) return mainTranslation;
    return formTranslations[language]?.[key as FormTranslationKey]
      ?? formTranslations.en[key as FormTranslationKey]
      ?? key;
  };
}
